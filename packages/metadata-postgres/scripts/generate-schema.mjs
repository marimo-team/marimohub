import { readFile, writeFile } from 'node:fs/promises';
const root = new URL('../', import.meta.url);
const sources = await Promise.all(
	['001-initial.sql', '002-deployment-guard.sql', '003-transfer-states.sql'].map((name) =>
		readFile(new URL(`sql/${name}`, root), 'utf8'),
	),
);
await writeFile(
	new URL('src/schema.ts', root),
	`// Generated by scripts/generate-schema.mjs; SQL files are authoritative.\nexport const migrationSources: readonly string[] = ${JSON.stringify(sources)};\n`,
);
